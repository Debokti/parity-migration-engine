DROP ALL OBJECTS;
CREATE TABLE IF NOT EXISTS invoices (
  id VARCHAR(40) PRIMARY KEY, ref VARCHAR(40) UNIQUE NOT NULL,
  status VARCHAR(30) NOT NULL, currency VARCHAR(3) NOT NULL,
  amount DECIMAL(14,2) NOT NULL, financed_amount DECIMAL(14,2) NOT NULL
);
CREATE TABLE IF NOT EXISTS beneficiaries (
  code VARCHAR(40) PRIMARY KEY,
  account_name VARCHAR(120) NOT NULL,
  currency VARCHAR(3) NOT NULL
);
CREATE TABLE IF NOT EXISTS drawdown_requests (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ref VARCHAR(40) UNIQUE NOT NULL, submission_token VARCHAR(100) UNIQUE NOT NULL,
  currency VARCHAR(3) NOT NULL, requested_amount DECIMAL(14,2) NOT NULL,
  discount_fee DECIMAL(14,2) NOT NULL, processing_fee DECIMAL(14,2) NOT NULL,
  net_payout DECIMAL(14,2) NOT NULL, tenor_days INT NOT NULL,
  beneficiary_code VARCHAR(40) NOT NULL, terms_acknowledged BOOLEAN NOT NULL,
  created_at TIMESTAMP NOT NULL,
  approval_stage VARCHAR(30) NOT NULL DEFAULT 'PENDING_CHECKER_1',
  created_by VARCHAR(40),
  amended_by VARCHAR(40),
  checker1_by VARCHAR(40),
  checker2_by VARCHAR(40),
  rejection_reason VARCHAR(500)
);
CREATE TABLE IF NOT EXISTS request_invoices (request_ref VARCHAR(40), invoice_ref VARCHAR(40),
  PRIMARY KEY(request_ref, invoice_ref));
CREATE TABLE IF NOT EXISTS attachments (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, request_ref VARCHAR(40),
  category VARCHAR(30) NOT NULL, filename VARCHAR(255) NOT NULL,
  file_type VARCHAR(100) NOT NULL, size_bytes BIGINT NOT NULL
);
